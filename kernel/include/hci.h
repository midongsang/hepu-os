/* HCI命令包结构 */
typedef struct {
    uint16_t opcode;
    uint8_t  param_len;
    uint8_t  params[255];
} hci_command_packet_t;

/* HCI事件包结构 */
typedef struct {
    uint8_t  event_code;
    uint8_t  param_len;
    uint8_t  params[255];
} hci_event_packet_t;

/* HCI ACL数据包结构 */
typedef struct {
    uint16_t handle_flags;  /* 12位handle + 4位flag */
    uint16_t data_len;
    uint8_t  data[1021];
} hci_acl_packet_t;

/* 蓝牙地址 */
typedef struct {
    uint8_t addr[6];
} hci_bdaddr_t;

/* 函数声明 */

/* 构建HCI命令包 */
int hci_build_command(uint16_t opcode, const void *params, uint8_t param_len,
                      uint8_t *out_buf, int out_buf_len);

/* 解析HCI事件包 */
int hci_parse_event(const uint8_t *data, int len, hci_event_packet_t *event);

/* 获取事件中的状态码 */
uint8_t hci_get_command_status(const hci_event_packet_t *event);

/* 获取命令完成事件中的opcode */
uint16_t hci_get_command_complete_opcode(const hci_event_packet_t *event);

/* Inquiry命令参数 */
typedef struct {
    uint32_t lap;           /* LAP（0x9E8B33 = 通用查询） */
    uint8_t  inquiry_length; /* 查询时长（1.28秒单位） */
    uint8_t  num_responses;  /* 最大响应数（0=无限） */
} hci_inquiry_params_t;

/* 创建连接命令参数 */
typedef struct {
    hci_bdaddr_t bdaddr;
    uint16_t packet_type;
    uint8_t  page_scan_repetition_mode;
    uint8_t  page_scan_mode;
    uint16_t clock_offset;
    uint8_t  allow_role_switch;
} hci_create_conn_params_t;

/* 断开连接命令参数 */
typedef struct {
    uint16_t handle;
    uint8_t  reason;
} hci_disconnect_params_t;

/* 设置本地名称命令参数 */
typedef struct {
    char name[248];
} hci_set_local_name_params_t;

/* 写入扫描使能命令参数 */
typedef struct {
    uint8_t scan_enable;  /* 0=无, 1=仅查询扫描, 2=仅寻呼扫描, 3=两者 */
} hci_write_scan_enable_params_t;

/* 事件掩码（8字节） */
typedef struct {
    uint8_t mask[8];
} hci_event_mask_t;

/* 默认事件掩码（启用所有常用事件） */
#define HCI_DEFAULT_EVENT_MASK { \
    0xFF, 0xFF, 0xFB, 0xFF, 0x07, 0xF8, 0xBF, 0x3D \
}

