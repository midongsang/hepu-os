void gop_init(EFI_GRAPHICS_OUTPUT_PROTOCOL *gop)
{
    g_gop = gop;
    if (gop && gop->Mode && gop->Mode->Info) {
        g_width = gop->Mode->Info->HorizontalResolution;
        g_height = gop->Mode->Info->VerticalResolution;
        g_pitch = gop->Mode->Info->PixelsPerScanLine;
        g_fb = (UINT32 *)(UINTN)gop->Mode->FrameBufferBase;
    }
}

UINT32 gop_get_width(void) { return g_width; }
UINT32 gop_get_height(void) { return g_height; }

void gop_clear(UINT32 color)
{
    gop_fill_rect(0, 0, g_width, g_height, color);
}

void gop_fill_rect(int x, int y, int w, int h, UINT32 color)
{
    if (!g_fb) return;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > (int)g_width) w = g_width - x;
    if (y + h > (int)g_height) h = g_height - y;
    if (w <= 0 || h <= 0) return;

    for (int row = 0; row < h; row++) {
        UINT32 *ptr = g_fb + (y + row) * g_pitch + x;
        for (int col = 0; col < w; col++) {
            ptr[col] = color;
        }
    }
}

void gop_draw_pixel(int x, int y, UINT32 color)
{
    if (!g_fb) return;
    if (x < 0 || x >= (int)g_width || y < 0 || y >= (int)g_height) return;
    g_fb[y * g_pitch + x] = color;
}

void gop_draw_char(int x, int y, char c, UINT32 color)
{
    unsigned char uc = (unsigned char)c;
    int idx = uc - 32;
    if (idx < 0 || idx >= 95) return;  /* 只支持ASCII 32-126 */

    const unsigned char *glyph = font8x16[idx];
    for (int row = 0; row < 16; row++) {
        unsigned char bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                gop_draw_pixel(x + col, y + row, color);
            }
        }
    }
}

void gop_draw_string(int x, int y, const char *s, UINT32 color)
{
    if (!s) return;
    int cx = x;
    while (*s) {
        if (*s == '\n') {
            cx = x;
            y += 16;
        } else {
            gop_draw_char(cx, y, *s, color);
            cx += 8;
        }
        s++;
    }
}

static void num_to_str(UINT32 n, char *buf, int base, int uppercase)
{
    const char *digits = uppercase ? "0123456789ABCDEF" : "0123456789abcdef";
    char tmp[32];
    int i = 0;
    if (n == 0) { buf[0] = '0'; buf[1] = 0; return; }
    while (n > 0) {
        tmp[i++] = digits[n % base];
        n /= base;
    }
    for (int j = 0; j < i; j++) buf[j] = tmp[i-1-j];
    buf[i] = 0;
}

