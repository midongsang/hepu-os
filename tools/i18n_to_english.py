    result = text
    keys = sorted(W.keys(), key=len, reverse=True)
    def repl(m):
        seg = m.group(0)
        for k in keys:
            if k in seg:
                seg = seg.replace(k, '\x00' + W[k] + '\x00')
        seg = seg.replace('\x00', ' ')
